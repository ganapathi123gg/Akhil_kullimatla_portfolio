/**
 * Returns the unified complete archive containing:
 * - All videos from the Work page (Short films, fight scene, trailers, songs, teasers, reels)
 * - All modeling editorial shoots from the Work page
 * - All 44 videos from the Watch More Library
 * Every video is guaranteed to have the 'Youtube' section tag and all relevant category tags.
 */
export function getAllArchiveItems() {
  const normalizedProjects = (PROJECTS || []).map((p) => {
    const isModel = p.type === 'image' || p.category === 'Modeling'
    const cats = isModel ? ['Model'] : ['Youtube']

    if (!isModel) {
      const lower = `${p.category || ''} ${p.title || ''} ${(p.tags || []).join(' ')}`.toLowerCase()
      if (lower.includes('short film') || lower.includes('shortfilm')) cats.push('Shortfilms')
      if (lower.includes('trailer')) cats.push('Trailer')
      if (lower.includes('teaser') || lower.includes('glimpse')) cats.push('teaser')
      if (lower.includes('song') || lower.includes('music')) cats.push('Songs')
      if (lower.includes('comedy')) cats.push('Comedy')
      if (p.isReel || lower.includes('reel') || lower.includes('fight') || lower.includes('sketch')) cats.push('Reels')
      if (lower.includes('vlog')) cats.push('Vlog')
      if (lower.includes('review') || lower.includes('reaction')) cats.push('Movie Reviews')
    }

    let ytId = p.youtubeId
    if (!ytId && p.youtubeUrl) {
      const m = p.youtubeUrl.match(/(?:watch\?v=|youtu\.be\/)([\w-]{11})/)
      if (m) ytId = m[1]
    }

    return {
      ...p,
      id: `proj-${p.id}`,
      originalId: p.id,
      cover: p.cover || p.thumbnail || p.image,
      thumbnail: p.thumbnail || p.cover || p.image,
      youtubeId: ytId,
      categories: Array.from(new Set(cats)),
      primaryCategory: isModel ? 'MODEL' : (p.category ? p.category.toUpperCase() : 'SHORT FILM'),
      source: 'projects'
    }
  })

  const normalizedWatchMore = WATCH_MORE_VIDEOS.map((w) => ({
    ...w,
    primaryCategory: w.category || 'CINEMA',
    source: 'watch-more'
  }))

  return [...normalizedProjects, ...normalizedWatchMore]
}

